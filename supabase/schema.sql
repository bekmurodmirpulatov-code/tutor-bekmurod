create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'student' check (role in ('teacher','student')),
  level text not null default 'B2',
  created_at timestamptz not null default now()
);

create table if not exists public.homework (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  day_number integer check (day_number is null or day_number > 0),
  due_date timestamptz,
  material_path text,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  homework_id bigint not null references public.homework(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'assigned' check (status in ('assigned','submitted','graded','overdue')),
  assigned_at timestamptz not null default now(),
  unique(homework_id, student_id)
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint not null references public.assignments(id) on delete cascade,
  file_path text,
  answer_text text,
  score numeric(5,2) check (score is null or (score >= 0 and score <= 100)),
  feedback text,
  submitted_at timestamptz not null default now(),
  constraint submission_has_content check (file_path is not null or nullif(trim(answer_text), '') is not null)
);

create table if not exists public.progress (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  day_number integer not null check (day_number > 0),
  completed boolean not null default false,
  completed_at timestamptz,
  unique(student_id, day_number)
);

