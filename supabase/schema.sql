create or replace function public.current_user_is_teacher()
returns boolean language sql stable security definer set search_path = public, pg_temp
as $$ select exists (select 1 from public.profiles where id = (select auth.uid()) and role = 'teacher') $$;
grant execute on function public.current_user_is_teacher() to authenticated;

create or replace function public.create_student_profile()
returns trigger language plpgsql security definer set search_path = public, pg_temp
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (new.id, coalesce(nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''), split_part(new.email, '@', 1)), 'student')
  on conflict (id) do nothing;
  return new;
end;
$$;

 drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile after insert on auth.users for each row execute procedure public.create_student_profile();

create or replace function public.prevent_profile_role_change()
returns trigger language plpgsql set search_path = public, pg_temp
as $$
begin
  if new.role is distinct from old.role and (select auth.uid()) is not null then
    raise exception 'Profile roles can only be changed by an administrator';
  end if;
  return new;
end;
$$;
drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role before update on public.profiles for each row execute procedure public.prevent_profile_role_change();

create or replace function public.sync_submission_status()
returns trigger language plpgsql security definer set search_path = public, pg_temp
as $$
begin
  update public.assignments set status = 'submitted' where id = new.assignment_id and status <> 'graded';
  insert into public.progress (student_id, day_number, completed, completed_at)
  select a.student_id, h.day_number, true, now() from public.assignments a join public.homework h on h.id = a.homework_id
  where a.id = new.assignment_id and h.day_number is not null
  on conflict (student_id, day_number) do update set completed = true, completed_at = excluded.completed_at;
  return new;
end;
$$;
drop trigger if exists submission_updates_progress on public.submissions;
create trigger submission_updates_progress after insert on public.submissions for each row execute procedure public.sync_submission_status();

