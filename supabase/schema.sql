create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null check (role in ('teacher','student')),
  level text default 'B2',
  created_at timestamptz default now()
);

create table if not exists public.homework (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  day_number integer,
  due_date timestamptz,
  material_url text,
  created_by uuid references public.profiles(id),
  created_at timestamptz default now()
);

create table if not exists public.assignments (
  id bigint generated by default as identity primary key,
  homework_id bigint references public.homework(id) on delete cascade,
  student_id uuid references public.profiles(id) on delete cascade,
  status text default 'assigned' check (status in ('assigned','submitted','graded','overdue')),
  assigned_at timestamptz default now(),
  unique(homework_id, student_id)
);

create table if not exists public.submissions (
  id bigint generated by default as identity primary key,
  assignment_id bigint references public.assignments(id) on delete cascade,
  file_url text,
  answer_text text,
  submitted_at timestamptz default now()
);

create table if not exists public.progress (
  id bigint generated by default as identity primary key,
  student_id uuid references public.profiles(id) on delete cascade,
  day_number integer not null,
  completed boolean default false,
  completed_at timestamptz,
  unique(student_id, day_number)
);

alter table public.profiles enable row level security;
alter table public.homework enable row level security;
alter table public.assignments enable row level security;
alter table public.submissions enable row level security;
alter table public.progress enable row level security;

create policy "profiles own view" on public.profiles for select using (auth.uid() = id or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher'));
create policy "profiles own update" on public.profiles for update using (auth.uid() = id);
create policy "homework visible" on public.homework for select using (true);
create policy "teachers manage homework" on public.homework for all using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher'));
create policy "assignment access" on public.assignments for select using (student_id = auth.uid() or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher'));
create policy "teachers manage assignments" on public.assignments for all using (exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher'));
create policy "submission access" on public.submissions for all using (exists (select 1 from public.assignments a where a.id = assignment_id and (a.student_id = auth.uid() or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher'))));
create policy "progress access" on public.progress for all using (student_id = auth.uid() or exists (select 1 from public.profiles p where p.id = auth.uid() and p.role = 'teacher'));
